// Helper functions
function getSchoolByName(name) {
  return DYNASTY_SCHOOLS.find(s => s.name === name);
}

function calcTierScore(school) {
  const keys = ['tradition','nilBudget','facilities','brand','atmosphere','proProspects','academic','campusLife','playingTime','champContender','coachPrestige','confPrestige'];
  return keys.reduce((a,k) => a + (school[k]||50), 0) / keys.length;
}

function getTierStars(score) {
  if(score >= 88) return 5;
  if(score >= 76) return 4;
  if(score >= 64) return 3;
  if(score >= 52) return 2;
  return 1;
}

function getNilLabel(v) {
  if(v >= 90) return '$10M+';
  if(v >= 80) return '$6-10M';
  if(v >= 70) return '$4-6M';
  if(v >= 60) return '$2-4M';
  if(v >= 50) return '$1-2M';
  return '<$1M';
}

